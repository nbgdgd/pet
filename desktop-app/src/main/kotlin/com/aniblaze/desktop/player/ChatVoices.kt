package com.aniblaze.desktop.player

/**
 * Голоса виртуального чата: кто пишет, каким цветом, какими словами.
 *
 * Здесь только ДАННЫЕ и чистые функции — ни состояния, ни Compose. Всё, что решает
 * «когда и что показать», живёт в [ChatEngine]; всё, что решает «как нарисовать», —
 * в ChatPanel. Такое разделение позволило покрыть тестами именно поведение чата, а
 * не разметку.
 */

/** Что происходит на экране — от этого зависит и темп чата, и слова. */
internal enum class SceneMood(val key: String) {
    /** Опенинг. Определяется ТОЧНО — по интервалу AniSkip. */
    OPENING("opening"),

    /** Эндинг. Тоже точно. */
    ENDING("ending"),

    /** Драка, погоня, экшен. По измеренному движению и частоте смены плана. */
    FIGHT("fight"),

    /** Резкий поворот: жёсткая склейка после спокойного куска. */
    TWIST("twist"),

    /** Грустная сцена: темнее и спокойнее обычного, и надолго. */
    SAD("sad"),

    /** Смешной момент. ИЗ КАДРА НЕ ИЗМЕРЯЕТСЯ — см. [ChatEngine.arcMood]. */
    FUNNY("funny"),

    /** Подъём перед кульминацией. Тоже из расписания, а не из кадра. */
    HYPE("hype"),

    /** Обычный ход серии. */
    CALM("calm"),
    ;

    /** Во сколько раз чат оживает против спокойного темпа. */
    val tempo: Float
        get() = when (this) {
            FIGHT -> 3.2f
            TWIST -> 4.0f
            HYPE -> 2.4f
            FUNNY -> 2.6f
            OPENING -> 1.9f
            ENDING -> 1.2f
            SAD -> 0.7f
            CALM -> 1.0f
        }
}

/**
 * Манера общения виртуального зрителя.
 *
 * Персона выбирается один раз при «входе в чат» и больше не меняется: узнаваемость и
 * есть то, из-за чего чат ощущается людьми, а не генератором строк.
 */
