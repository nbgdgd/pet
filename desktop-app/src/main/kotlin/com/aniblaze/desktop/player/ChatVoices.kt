    val key: String,
    /** Значок у ника — короткая подпись вместо картинки. */
    val badge: String?,
    /** Доля таких зрителей в зале. */
    val share: Int,
    /** Множитель словоохотливости. */
    val talkative: Float,
) {
    /** Спокойный: пишет по делу и редко. */
    CALM("calm", null, 22, 0.7f),

    /** Токсичный: всем недоволен, но не переходит на людей. */
    TOXIC("toxic", null, 12, 1.2f),

    /** Мемный: живёт эмоциями и сокращениями. */
    MEME("meme", null, 20, 1.5f),

    /** Фанат персонажа: у него есть любимчик, и он о нём напоминает. */
    STAN("stan", "ФАН", 14, 1.3f),

    /** Новичок: смотрит впервые, всё спрашивает. */
    NEWBIE("newbie", "НОВЕНЬКИЙ", 12, 1.0f),

    /**
     * Спойлерщик. НИЧЕГО НЕ СПОЙЛЕРИТ ПО-НАСТОЯЩЕМУ, и не может: сюжета серии
