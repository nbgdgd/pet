/** Части, из которых собираются ники. Комбинаций — десятки тысяч. */
internal object ChatNicks {
    private val prefixes = listOf(
        "", "", "", "xX", "not", "real", "just", "mr", "lil", "dark", "neo", "big",
        "sad", "cool", "anti", "ultra", "mega", "super", "old", "new", "the",
    )
    private val roots = listOf(
        "senpai", "kuro", "shiro", "yuki", "kage", "ramen", "otaku", "sakura",
        "tanuki", "kitsune", "onigiri", "matcha", "gojo", "levi", "titan", "shinobi",
        "katana", "sensei", "hikari", "tsuki", "sora", "hoshi", "neko", "inu",
        "vasya", "petrovich", "borsch", "pelmeni", "medved", "kvass", "batya",
        "diman", "seryoga", "anon", "lurker", "pixel", "byte", "glitch", "vhs",
        "manga", "isekai", "waifu", "husbando", "arc", "filler", "canon", "opening",
    )
    private val suffixes = listOf(
        "", "", "", "", "_", "chan", "kun", "san", "sama", "tv", "live", "ru",
        "228", "777", "2007", "1337", "99", "42", "_ua", "xd",
    )

    /** Ник по номеру зрителя: одинаковый номер — одинаковый ник, всегда. */
    fun of(seed: Long): String {
        val a = ((seed * 6364136223846793005L + 1442695040888963407L) ushr 16)
        val b = ((seed * 2862933555777941757L + 3037000493L) ushr 16)
        val c = ((seed * 6906969069L + 1234567L) ushr 16)
        val prefix = prefixes[(a % prefixes.size).toInt().absMod(prefixes.size)]
        val root = roots[(b % roots.size).toInt().absMod(roots.size)]
        val suffix = suffixes[(c % suffixes.size).toInt().absMod(suffixes.size)]
        val nick = prefix + root + suffix
        return nick.replaceFirstChar { it.uppercase() }
    }

    private fun Int.absMod(bound: Int): Int = ((this % bound) + bound) % bound
}

