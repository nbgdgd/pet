    private val exact = rules.filterNot { placeholder.containsMatchIn(it.source) }.associate { it.source to it.target }
    private val templates = rules.filter { placeholder.containsMatchIn(it.source) }

    fun text(character: String, original: String): String {
        if (character != "drizz") return original
        exact[original]?.let { return it }
        if (original.startsWith("Доброе утро! ")) return "Доброе утро, уёбище! " + text(character, original.removePrefix("Доброе утро! "))
        if (original.startsWith("Доброй ночи. ")) return "Доброй ночи, пидарас. " + text(character, original.removePrefix("Доброй ночи. "))
        // These are composed messages. Translate only the known phrase, never the title.
        for (phrase in DrizzPhrases.titles) {
            if (original.startsWith('«') && original.endsWith("». $phrase"))
                return original.removeSuffix(phrase) + exact.getValue(phrase)
        }
        for (phrase in PetPhrases.NEW_EPISODE) {
            if (original.startsWith("$phrase В избранном: "))
                return exact.getValue(phrase) + " " + text(character, original.removePrefix("$phrase "))
        }
        return templates.firstNotNullOfOrNull { it.apply(original) } ?: original
    }
