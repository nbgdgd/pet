    private val placeholder = Regex("\\[([^]]+)]")
    private class Rule(val source: String, val target: String) {
        private val tokens = placeholder.findAll(source).toList()
        private val pattern = if (tokens.isEmpty()) null else Regex(buildString {
            var offset = 0
            for (token in tokens) {
                append(Regex.escape(source.substring(offset, token.range.first)))
                append("(.*?)")
                offset = token.range.last + 1
            }
            append(Regex.escape(source.substring(offset)))
        }, RegexOption.DOT_MATCHES_ALL)

        fun apply(text: String): String? {
            val match = pattern?.matchEntire(text) ?: return null
            val values = tokens.mapIndexed { index, token -> token.value to match.groupValues[index + 1] }.toMap()
            return placeholder.replace(target) { values[it.value] ?: it.value }
        }
    }

