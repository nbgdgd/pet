package com.aniblaze.featureplayer

import com.aniblaze.aggregator.model.StreamVariant

/**
 * Лестница качеств: разбор подписи, выбор сохранённого предпочтения и склейка
 * дописанных вариантов.
 *
 * Вынесено из PlayerViewModel отдельными чистыми функциями по одной причине: всё это
 * СТРОКОВАЯ работа над подписями, которые каждый источник пишет по-своему («720p» у
 * Kodik, «auto» у прямой ссылки Anixart, «1080p · AniLibria» у дописанного варианта), и
 * ошибиться здесь можно молча — плеер продолжит играть, просто не то и не в том
 * качестве.
 */

/**
 * Высота кадра из подписи варианта. 0 = в подписи числа нет.
 *
 * Ноль здесь означает ровно «неизвестно», а не «плохо»: так подписан вариант «auto» —
 * прямая ссылка, у которой качество вообще не заявлено.
 */
internal fun qualityHeightOf(label: String): Int =
    HEIGHT_IN_LABEL.find(label)?.value?.toIntOrNull() ?: 0

/** Три-четыре цифры подряд — это и есть высота кадра в подписи варианта. */
private val HEIGHT_IN_LABEL = Regex("""\d{3,4}""")

/**
 * Стоит ли идти к AniLibria за 1080p.
 *
 * Раньше условие звучало как «максимальная известная высота меньше 1080», и высота
 * бралась через `maxOrNull() ?: return`. Из-за этого `return` функция МОЛЧА ВЫХОДИЛА в
 * двух случаях сразу: список вариантов пуст и ни в одной подписи нет числа. Второй —
 * это прямая ссылка Anixart, которая подписана «auto»; на ней улучшение не срабатывало
 * никогда, хотя именно там оно нужнее всего — качество неизвестно и, судя по потоку,
 * невысокое.
 *
 * Теперь отказ только один: мы ТОЧНО ЗНАЕМ, что 1080p и выше уже есть. Неизвестное
 * качество — повод сходить и спросить, а не повод сдаться. Цена ошибки несимметрична:
 * лишний запрос это один HTTP вне критического пути, а пропущенное улучшение человек
 * не увидит вовсе.
 */
internal fun shouldTryHiRes(variants: List<StreamVariant>): Boolean =
    variants.none { qualityHeightOf(it.quality) >= HI_RES_HEIGHT }

/** С какой высоты вариант считается «уже хорошим». */
internal const val HI_RES_HEIGHT = 1080

/**
 * Вариант под сохранённое предпочтение — по ВЫСОТЕ, а не по подписи целиком.
 *
 * Сравнение строк здесь было тихой поломкой. Стоит выбрать дописанный «1080p ·
 * AniLibria», и в настройки уезжала эта же строка. Дальше на каждой следующей серии
 * предпочтение сверялось с подписями источника («720p», «1080p») точным равенством, не
 * совпадало никогда — и авто-выбор качества переставал работать совсем, включая
 * честные 1080p от самого источника. Одно нажатие ломало настройку навсегда.
 *
 * Человек выбирает высоту, а не текст на кнопке. Поэтому [preferredQualityKey] кладёт
 * в настройки «1080p», а сюда приходит любая подпись с тем же числом.
 */
internal fun pickPreferred(variants: List<StreamVariant>, preferred: String): StreamVariant? {
    if (preferred.isBlank() || variants.isEmpty()) return null
    val wanted = qualityHeightOf(preferred)
    // Подпись без числа («auto») сравнима только сама с собой.
    if (wanted == 0) return variants.firstOrNull { it.quality.equals(preferred, ignoreCase = true) }
    return variants.firstOrNull { it.quality.equals(preferred, ignoreCase = true) }
        ?: variants.firstOrNull { qualityHeightOf(it.quality) == wanted }
}

/**
 * Что записать в настройки как «предпочитаемое качество».
 *
 * Только высота: «1080p · AniLibria» превращается в «1080p». Источник, приписка и
 * прочее оформление подписи к желанию человека отношения не имеют, а в настройках
 * живут долго и переживают смену источника.
 */
internal fun preferredQualityKey(label: String): String {
    val height = qualityHeightOf(label)
    return if (height > 0) "${height}p" else label
}

/**
 * Склейка дописанных вариантов с теми, что дал источник.
 *
 * Сортировка по убыванию высоты — не косметика. Весь код вокруг считает первый элемент
 * лучшим (`variants.firstOrNull()` в источниках и в подборе 1080p), а простое
 * дописывание в конец ставило 1080p ПОСЛЕ 480p: и в списке выбора он оказывался внизу,
 * и «лучший» по соглашению переставал быть лучшим.
 *
 * Варианты без числа в подписи уходят вниз: «auto» это неизвестность, и ставить её
 * впереди заявленного 1080p не за что. Порядок равных сохраняется.
 */
internal fun mergeVariants(base: List<StreamVariant>, extra: List<StreamVariant>): List<StreamVariant> =
    (base + extra)
        .distinctBy { it.url }
        .sortedByDescending { qualityHeightOf(it.quality) }
