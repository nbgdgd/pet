def _alternation(keys):
    """Один общий шаблон вместо сотни отдельных: длинные ключи раньше коротких."""
    if not keys:
        return None
    ordered = sorted(keys, key=len, reverse=True)
    return re.compile(
        r"\b(?:" + "|".join(re.escape(k) for k in ordered) + r")\b",
        re.IGNORECASE,
    )


class Normalizer:
    """
    Приведение сырого текста STT к канонической форме.

    Замены делаются ОДНИМ проходом на словарь, а не циклом из ~160
    отдельных re.sub. Это не только в разы быстрее: при цикле результат
    одной замены тут же попадал под следующее правило (каскад), и одна и
    та же фраза нормализовалась по-разному в зависимости от порядка
    ключей в словаре.
    """

    def __init__(self):
        self._build_error_patterns()
        self._build_phonetic_patterns()
        self._build_noise_patterns()

    def _build_error_patterns(self):
        self._error_re = _alternation(STT_ERRORS.keys())

    def _build_phonetic_patterns(self):
        self._phon_re = _alternation(PHONETIC.keys())

    def _build_noise_patterns(self):
        self._noise_re = _alternation(NOISE_WORDS)

    @staticmethod
    def _sub(pattern, table, text):
        if pattern is None:
            return text
        return pattern.sub(lambda m: table.get(m.group(0).lower(), m.group(0)), text)

    def normalize(self, text: str) -> str:
        if not text:
            return ""
        t = text.lower().strip()
        t = re.sub(r"[^\w\s]", " ", t)
        t = self._sub(self._error_re, STT_ERRORS, t)      # типичные ошибки STT
        t = self._sub(self._phon_re, PHONETIC, t)         # фонетические варианты
        if self._noise_re is not None:                    # слова-паразиты
            t = self._noise_re.sub("", t)
        return re.sub(r"\s+", " ", t).strip()

    def extract_keywords(self, text: str) -> set:
        """Извлечение значимых ключевых слов из текста."""
        t = self.normalize(text)
        words = set(t.split())
        # Убираем слишком короткие слова (1 буква)
        words = {w for w in words if len(w) > 1}
        return words

    def expand_short_aliases(self, text: str) -> str:
        """Замена коротких алиасов на полные формы."""
        t = text.lower().strip()
        words = t.split()
        # Проверяем каждое слово как возможный алиас
        expanded = []
        for w in words:
            if w in SHORT_ALIASES:
                expanded.append(SHORT_ALIASES[w])
            else:
                expanded.append(w)
        return " ".join(expanded)
